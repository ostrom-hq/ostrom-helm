#!/bin/sh
# Ostrom self-hosted: writes .env with fresh secrets (once), then starts everything.
# Usage: ./install.sh [--no-start]
set -eu
cd "$(dirname "$0")"
command -v docker >/dev/null 2>&1 || { echo "docker is required: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "docker compose v2 is required" >&2; exit 1; }

secret() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; }

umask 077
if [ ! -f .env ]; then
  {
    echo "# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep it: losing it locks you out of the data."
    echo "OSTROM_VERSION=${OSTROM_VERSION:-latest}"
    echo "OSTROM_SCHEME=${OSTROM_SCHEME:-http}"
    echo "OSTROM_API_HOST=${OSTROM_API_HOST:-api.localhost}"
    echo "OSTROM_APP_HOST=${OSTROM_APP_HOST:-app.localhost}"
    echo "OSTROM_SSO_HOST=${OSTROM_SSO_HOST:-sso.localhost}"
  } > .env
  echo "Wrote .env."
else
  echo ".env exists: keeping its secrets."
fi
# Each secret is generated once; a missing one (an older .env) is added, an existing one never changes.
for pair in POSTGRES_PASSWORD:32 OSTROM_OWNER_PASSWORD:32 OSTROM_APP_PASSWORD:32 POLIS_DB_PASSWORD:32 \
            POLIS_API_KEY:48 POLIS_NEXTAUTH_SECRET:48 POLIS_DB_ENCRYPTION_KEY:32; do
  name=${pair%%:*}; length=${pair#*:}
  grep -q "^${name}=" .env || echo "${name}=$(secret "$length")" >> .env
done
chmod 600 .env

[ "${1:-}" = "--no-start" ] && exit 0
docker compose up -d --wait
# shellcheck source=/dev/null
. ./.env
echo
echo "Ostrom is up:"
echo "  console  ${OSTROM_SCHEME}://${OSTROM_APP_HOST}"
echo "  API      ${OSTROM_SCHEME}://${OSTROM_API_HOST}"
